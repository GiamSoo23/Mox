#!/usr/bin/env python3
"""Generates BundledMigrations.swift and BundledFunctions.swift from backend/supabase/.

The setup wizard (#22) applies these to the user's project, so the Mac app
carries them as code: Mox.app is assembled from the binary alone, so SwiftPM
resource bundles wouldn't ship. MoxCoreTests fails if this file drifts from
the backend, so run this after changing a migration:

    python3 desktop/macos/scripts/sync-migrations.py
"""
import pathlib

root = pathlib.Path(__file__).resolve().parents[3]
migrations = sorted((root / "backend/supabase/migrations").glob("*.sql"))
out = root / "desktop/macos/Sources/MoxCore/BundledMigrations.swift"

parts = [
    "// Generated by desktop/macos/scripts/sync-migrations.py — do not edit.",
    "// Source: backend/supabase/migrations/. A test checks they match.",
    "",
    "/// The backend migrations, in order, for the setup wizard to apply (#22, #80).",
    "public enum BundledMigrations {",
    "    public static let all: [(version: String, name: String, sql: String)] = [",
]
for path in migrations:
    sql = path.read_text()
    assert '"""#' not in sql, f"{path.name} contains a sequence that breaks the raw string"
    version, _, name = path.stem.partition("_")
    parts.append(f'        (version: "{version}", name: "{name}", sql: #"""')
    parts.append(sql.rstrip("\n"))
    parts.append('"""#),')
parts += ["    ]", "}", ""]
out.write_text("\n".join(parts))
print(f"wrote {out.relative_to(root)} ({len(migrations)} migrations)")

# The Edge Functions setup deploys (#27, #54), without their tests.
fn_root = root / "backend/supabase/functions"
fn_out = root / "desktop/macos/Sources/MoxCore/BundledFunctions.swift"
parts = [
    "// Generated by desktop/macos/scripts/sync-migrations.py — do not edit.",
    "// Source: backend/supabase/functions/. A test checks they match.",
    "",
    "/// The Edge Functions setup deploys to the user's project (#27, #54).",
    "public enum BundledFunctions {",
    "    public static let all: [(slug: String, files: [(name: String, content: String)])] = [",
]
count = 0
for fn_dir in sorted(p for p in fn_root.iterdir() if p.is_dir()):
    parts.append(f'        (slug: "{fn_dir.name}", files: [')
    for path in sorted(p for p in fn_dir.glob("*.ts") if not p.name.endswith("_test.ts")):
        code = path.read_text()
        assert '"""#' not in code
        parts.append(f'            (name: "{path.name}", content: #"""')
        parts.append(code.rstrip("\n"))
        parts.append('"""#),')
    parts.append("        ]),")
    count += 1
parts += ["    ]", "}", ""]
fn_out.write_text("\n".join(parts))
print(f"wrote {fn_out.relative_to(root)} ({count} functions)")
